import type { ParsedInvoice, ReminderDraft, ReminderTone } from "./ai-schema";

/** Rule-based DEMO SIMULATION used only when hosted AI is unavailable. */
export function localParseInvoice(text: string): ParsedInvoice {
  const assumptions: string[] = ["Generated by local demo rules, not AI."];
  const qtyMatch = text.match(/(\d+(?:\.\d+)?)\s*(hours?|hrs?|h\b|days?|units?|x)/i);
  const rateMatch = text.match(/\$\s?(\d+(?:,\d{3})*(?:\.\d+)?)/);
  const clientMatch = text.match(/\bfor\s+([A-Z][\w&.-]*(?:\s+[A-Z][\w&.-]*)*)/);
  const dueMatch = text.match(/due\s+in\s+(\d+)\s*days?/i);
  const emailMatch = text.match(/[\w.+-]+@[\w-]+\.[\w.]+/);

  const quantity = qtyMatch ? Number(qtyMatch[1]) : 1;
  if (!qtyMatch) assumptions.push("No quantity found; assumed 1.");
  const unitPrice = rateMatch ? Number((rateMatch[1] ?? "0").replace(/,/g, "")) : 0;
  if (!rateMatch) assumptions.push("No price found; set to $0 — please edit.");

  let description = text
    .replace(/(\d+(?:\.\d+)?)\s*(hours?|hrs?|h\b|days?|units?|x)\s*(of)?/i, "")
    .replace(/at\s+\$[\d,.]+\s*(\/\s*\w+|per\s+\w+)?/i, "")
    .replace(/\bfor\s+[A-Z][\w&.-]*(?:\s+[A-Z][\w&.-]*)*/, "")
    .replace(/due\s+in\s+\d+\s*days?/i, "")
    .replace(emailMatch?.[0] ?? "\u0000", "")
    .replace(/\s+/g, " ")
    .trim();
  description = description ? description.charAt(0).toUpperCase() + description.slice(1) : "Services";

  const clientName = clientMatch?.[1] ?? "";
  if (!clientName) assumptions.push("No client name found.");
  const dueInDays = dueMatch ? Number(dueMatch[1]) : 30;
  if (!dueMatch) assumptions.push("No due date found; assumed 30 days.");
  assumptions.push("Currency assumed USD, no tax applied.");

  return {
    clientName,
    clientEmail: emailMatch?.[0] ?? null,
    items: [{ description, quantity, unitPrice }],
    dueInDays,
    taxRate: null,
    notes: null,
    assumptions,
    confidence: rateMatch && clientName ? "medium" : "low",
  };
}

export function localReminder(
  tone: ReminderTone,
  ctx: { clientName: string; number: string; amount: string; dueDate: string; daysOverdue: number; businessName: string },
): ReminderDraft {
  const first = ctx.clientName.split(" ")[0] || "there";
  const subjects: Record<ReminderTone, string> = {
    friendly: `Quick reminder: invoice ${ctx.number}`,
    firm: `Payment overdue: invoice ${ctx.number}`,
    final: `Final notice: invoice ${ctx.number} is ${ctx.daysOverdue} days overdue`,
  };
  const bodies: Record<ReminderTone, string> = {
    friendly: `Hi ${first},\n\nHope you're doing well! Just a friendly nudge that invoice ${ctx.number} for ${ctx.amount} was due on ${ctx.dueDate}. If it's already on its way, thank you — please ignore this.\n\nYou can pay securely using the link in the original invoice email. Let me know if anything is unclear.\n\nThanks,\n${ctx.businessName}`,
    firm: `Hi ${first},\n\nInvoice ${ctx.number} for ${ctx.amount} is now ${ctx.daysOverdue} days past its due date of ${ctx.dueDate}. Could you please arrange payment this week, or let me know when I can expect it?\n\nThe payment link is in the original invoice email.\n\nBest regards,\n${ctx.businessName}`,
    final: `Hello ${first},\n\nThis is a final reminder that invoice ${ctx.number} for ${ctx.amount} remains unpaid, ${ctx.daysOverdue} days after the ${ctx.dueDate} due date. Please complete payment within 5 business days or contact me to agree a payment plan.\n\nRegards,\n${ctx.businessName}`,
  };
  return { subject: subjects[tone], body: bodies[tone] };
}